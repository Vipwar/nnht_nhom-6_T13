"""
JFLAP (.jff) XML Exporter and Round-Trip Importer for Epsilon-NFA and DFA.

Allows students and instructors to open any automaton generated by our engine
directly inside JFLAP 7.x for independent visual and behavioral verification
(aligning with Section 2 of the UEH Final Project Guidelines), and supports
round-trip XML import to mathematically verify exported .jff files.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from collections import deque
from typing import Dict, FrozenSet, List, Optional, Set, Tuple
from xml.sax.saxutils import escape

from .models import (
    DFA,
    NFA,
    NON_ASCII,
    SIGMA,
    AcceptInfo,
    compute_alphabet_partition,
    format_charset,
)
from .regex_parser import CharSetNode, parse_regex


def _xml_escape(text: str) -> str:
    """
    Escape XML special characters (<, >, &, ", ') as well as control characters
    (\r, \n, \t, \v, \f) using numeric character references so XML 1.0 parsers
    preserve exact whitespace characters without normalization loss.
    """
    escaped = escape(text, {'"': "&quot;", "'": "&apos;"})
    return (
        escaped.replace("\r", "&#13;")
        .replace("\n", "&#10;")
        .replace("\t", "&#9;")
        .replace("\v", "&#11;")
        .replace("\f", "&#12;")
    )


def _compute_layered_layout(
    states: Set[int],
    start_state: int,
    adjacency: Dict[int, List[int]],
) -> Dict[int, Tuple[float, float]]:
    """Compute clean left-to-right layered (x, y) coordinates via BFS for JFLAP."""
    levels: Dict[int, int] = {start_state: 0}
    queue: deque[int] = deque([start_state])
    while queue:
        u = queue.popleft()
        for v in adjacency.get(u, ()):
            if v not in levels:
                levels[v] = levels[u] + 1
                queue.append(v)

    max_lvl = max(levels.values(), default=0)
    for q in sorted(states):
        if q not in levels:
            max_lvl += 1
            levels[q] = max_lvl

    by_level: Dict[int, List[int]] = {}
    for q, lvl in levels.items():
        by_level.setdefault(lvl, []).append(q)

    coords: Dict[int, Tuple[float, float]] = {}
    for lvl, qlist in by_level.items():
        qlist.sort()
        x = 80.0 + lvl * 130.0
        total_h = (len(qlist) - 1) * 95.0
        y_start = max(60.0, 260.0 - total_h / 2.0)
        for idx, q in enumerate(qlist):
            coords[q] = (x, y_start + idx * 95.0)
    return coords


def export_nfa_to_jflap(nfa: NFA, expand_char_classes: bool = False) -> str:
    """
    Serialize an Epsilon-NFA to JFLAP .jff XML format.
    - Empty `<read/>` represents epsilon transitions in JFLAP.
    - If `expand_char_classes=True`, expands character sets into individual
      single-character transitions so JFLAP and round-trip verifiers can simulate
      strings directly.
    """
    adj: Dict[int, List[int]] = {
        src: [dst for _, dst, _ in edges] for src, edges in nfa.transitions.items()
    }
    coords = _compute_layered_layout(nfa.states, nfa.start_state, adj)

    lines: List[str] = [
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!-- Generated by T13 Automata-based Lexical Analyzer -->",
        "<structure>",
        "  <type>fa</type>",
        "  <automaton>",
    ]

    for q in sorted(nfa.states):
        x, y = coords[q]
        acc = nfa.accept_states.get(q)
        lines.append(f'    <state id="{q}" name="q{q}">')
        lines.append(f"      <x>{x:.1f}</x>")
        lines.append(f"      <y>{y:.1f}</y>")
        if acc is not None:
            lines.append(f"      <label>{_xml_escape(acc.token_name)}</label>")
        if q == nfa.start_state:
            lines.append("      <initial/>")
        if acc is not None:
            lines.append("      <final/>")
        lines.append("    </state>")

    for src in sorted(nfa.transitions.keys()):
        for chars, dst, lbl in nfa.transitions[src]:
            if chars is None:
                lines.append("    <transition>")
                lines.append(f"      <from>{src}</from>")
                lines.append(f"      <to>{dst}</to>")
                lines.append("      <read/>")
                lines.append("    </transition>")
            elif expand_char_classes:
                for ch in sorted(chars, key=ord):
                    lines.append("    <transition>")
                    lines.append(f"      <from>{src}</from>")
                    lines.append(f"      <to>{dst}</to>")
                    lines.append(f"      <read>{_xml_escape(ch)}</read>")
                    lines.append("    </transition>")
            else:
                full_lbl = format_charset(chars, max_len=10000)
                lines.append("    <transition>")
                lines.append(f"      <from>{src}</from>")
                lines.append(f"      <to>{dst}</to>")
                lines.append(f"      <read>{_xml_escape(full_lbl)}</read>")
                lines.append("    </transition>")

    lines.extend(["  </automaton>", "</structure>"])
    return "\n".join(lines) + "\n"


def export_dfa_to_jflap(dfa: DFA, expand_char_classes: bool = False) -> str:
    """
    Serialize a DFA to JFLAP .jff XML format.
    """
    edges = dfa.compressed_edges()
    adj: Dict[int, List[int]] = {}
    for src, dst, _, _ in edges:
        adj.setdefault(src, []).append(dst)
    coords = _compute_layered_layout(dfa.states, dfa.start_state, adj)

    lines: List[str] = [
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!-- Generated by T13 Automata-based Lexical Analyzer -->",
        "<structure>",
        "  <type>fa</type>",
        "  <automaton>",
    ]

    for q in sorted(dfa.states):
        x, y = coords[q]
        acc = dfa.accept_states.get(q)
        lines.append(f'    <state id="{q}" name="D{q}">')
        lines.append(f"      <x>{x:.1f}</x>")
        lines.append(f"      <y>{y:.1f}</y>")
        if acc is not None:
            lines.append(f"      <label>{_xml_escape(acc.token_name)}</label>")
        if q == dfa.start_state:
            lines.append("      <initial/>")
        if acc is not None:
            lines.append("      <final/>")
        lines.append("    </state>")

    for src, dst, fset, _lbl in edges:
        if expand_char_classes:
            for ch in sorted(fset, key=ord):
                lines.append("    <transition>")
                lines.append(f"      <from>{src}</from>")
                lines.append(f"      <to>{dst}</to>")
                lines.append(f"      <read>{_xml_escape(ch)}</read>")
                lines.append("    </transition>")
        else:
            full_lbl = format_charset(fset, max_len=10000)
            lines.append("    <transition>")
            lines.append(f"      <from>{src}</from>")
            lines.append(f"      <to>{dst}</to>")
            lines.append(f"      <read>{_xml_escape(full_lbl)}</read>")
            lines.append("    </transition>")

    lines.extend(["  </automaton>", "</structure>"])
    return "\n".join(lines) + "\n"


def _decode_jflap_read_symbol(txt: str) -> FrozenSet[str]:
    """Decode a JFLAP `<read>` tag text into a character set."""
    if len(txt) == 1:
        if txt == "␣":
            return frozenset({" "})
        return frozenset({txt})
    special_map = {
        "\\n": "\n",
        "\\t": "\t",
        "\\r": "\r",
        "\\v": "\v",
        "\\f": "\f",
        "\\\\": "\\",
        "\\u0080+": NON_ASCII,
        "Σ": None,
        ".": "DOT",
    }
    if txt in special_map:
        val = special_map[txt]
        if val is None:
            return SIGMA
        if val == "DOT":
            return SIGMA - {"\n"}
        return frozenset({val})
    if txt.startswith("[") and txt.endswith("]") and not txt.endswith("...]"):
        negated = txt.startswith("[^")
        inner = txt[2:-1] if negated else txt[1:-1]
        has_non_ascii = "\\u0080+" in inner
        inner_clean = inner.replace("\\u0080+", "")
        if negated:
            if not inner_clean:
                base = SIGMA
            else:
                node = parse_regex(f"[^{inner_clean}]")
                base = node.chars if isinstance(node, CharSetNode) else frozenset()
            if has_non_ascii:
                base = base - {NON_ASCII}
            return base
        else:
            if not inner_clean:
                base = frozenset()
            else:
                node = parse_regex(f"[{inner_clean}]")
                base = node.chars if isinstance(node, CharSetNode) else frozenset()
            if has_non_ascii:
                base = base | {NON_ASCII}
            return base
    return frozenset({txt[0]})


def import_jflap_to_nfa(xml_str: str) -> NFA:
    """
    Parse a JFLAP 7.x `.jff` XML string back into an NFA object for round-trip verification.
    """
    root = ET.fromstring(xml_str)
    if root.findtext("type") != "fa":
        raise ValueError("File JFLAP không phải loại Finite Automaton (<type>fa</type>)")

    automaton = root.find("automaton")
    if automaton is None:
        raise ValueError("File JFLAP thiếu thẻ <automaton>")

    states: Set[int] = set()
    start_state: Optional[int] = None
    accept_states: Dict[int, AcceptInfo] = {}

    for idx, st_elem in enumerate(automaton.findall("state")):
        sid = int(st_elem.attrib["id"])
        states.add(sid)
        if st_elem.find("initial") is not None:
            start_state = sid
        if st_elem.find("final") is not None:
            tok_name = (st_elem.findtext("label") or "ACCEPT").strip()
            accept_states[sid] = AcceptInfo(token_name=tok_name, priority=idx)

    if start_state is None:
        start_state = min(states) if states else 0

    eps_edges: Dict[int, List[int]] = {}
    char_grouped: Dict[Tuple[int, int], Set[str]] = {}

    for tr_elem in automaton.findall("transition"):
        src = int(tr_elem.findtext("from") or "0")
        dst = int(tr_elem.findtext("to") or "0")
        states.add(src)
        states.add(dst)
        read_elem = tr_elem.find("read")
        if read_elem is None or read_elem.text is None or read_elem.text == "":
            eps_edges.setdefault(src, []).append(dst)
        else:
            cset = _decode_jflap_read_symbol(read_elem.text)
            char_grouped.setdefault((src, dst), set()).update(cset)

    nfa = NFA(
        states=states,
        start_state=start_state,
        accept_states=accept_states,
        name="Imported JFLAP NFA",
    )
    for src, dsts in sorted(eps_edges.items()):
        for dst in dsts:
            nfa.add_epsilon(src, dst)
    for (src, dst), cset in sorted(char_grouped.items()):
        fset = frozenset(cset)
        nfa.add_transition(src, dst, fset, format_charset(fset))
    return nfa


def import_jflap_to_dfa(xml_str: str) -> DFA:
    """
    Parse a JFLAP 7.x `.jff` XML string back into a DFA object for round-trip verification.
    """
    root = ET.fromstring(xml_str)
    if root.findtext("type") != "fa":
        raise ValueError("File JFLAP không phải loại Finite Automaton (<type>fa</type>)")

    automaton = root.find("automaton")
    if automaton is None:
        raise ValueError("File JFLAP thiếu thẻ <automaton>")

    states: Set[int] = set()
    start_state: Optional[int] = None
    accept_states: Dict[int, AcceptInfo] = {}

    for idx, st_elem in enumerate(automaton.findall("state")):
        sid = int(st_elem.attrib["id"])
        states.add(sid)
        if st_elem.find("initial") is not None:
            start_state = sid
        if st_elem.find("final") is not None:
            tok_name = (st_elem.findtext("label") or "ACCEPT").strip()
            accept_states[sid] = AcceptInfo(token_name=tok_name, priority=idx)

    if start_state is None:
        start_state = min(states) if states else 0

    edge_charsets: Dict[Tuple[int, int], Set[str]] = {}
    for tr_elem in automaton.findall("transition"):
        src = int(tr_elem.findtext("from") or "0")
        dst = int(tr_elem.findtext("to") or "0")
        states.add(src)
        states.add(dst)
        read_elem = tr_elem.find("read")
        if read_elem is None or read_elem.text is None or read_elem.text == "":
            raise ValueError("DFA trong JFLAP không được chứa chuyển tiếp ε (<read/> rỗng)")
        cset = _decode_jflap_read_symbol(read_elem.text)
        edge_charsets.setdefault((src, dst), set()).update(cset)

    frozen_sets = [frozenset(cs) for cs in edge_charsets.values() if cs]
    char_classes = compute_alphabet_partition(frozen_sets)
    representatives = [next(iter(cs)) for cs in char_classes]

    transitions: Dict[int, Dict[int, int]] = {q: {} for q in states}
    for (src, dst), cs in edge_charsets.items():
        for cid, rep in enumerate(representatives):
            if rep in cs:
                transitions.setdefault(src, {})[cid] = dst

    return DFA(
        states=states,
        start_state=start_state,
        accept_states=accept_states,
        char_classes=char_classes,
        transitions=transitions,
        name="Imported JFLAP DFA",
    )

